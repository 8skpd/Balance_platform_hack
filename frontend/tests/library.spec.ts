import {provisionAccount} from './test-accounts';
import {openTool,openMode,reveal} from './ui-navigation';
import { test, expect } from '@playwright/test';

test('restore an older version as a new immutable version', async ({page})=>{
  const request=page.request;
  await provisionAccount(request,{data:{username:'restore-'+Date.now(),display_name:'Restore',password:'Library-browser-password-42'}});
  const code="CHECK={'entrypoint':lambda m,p:[]}";
  const v1=await (await request.post('/api/check-library',{data:{name:'История',code,params:{threshold:1}}})).json();
  await request.post(`/api/check-library/${v1.check_id}/versions`,{data:{name:'История',code,params:{threshold:2},expected_version:1}});
  await page.goto('/?view=library');await page.getByRole('button',{name:'Проверки',exact:true}).click();
  await page.locator('.library-item').filter({hasText:'История'}).click();
  await page.getByLabel('Версия проверки',{exact:true}).selectOption('1');
  await expect(page.getByLabel('Параметры библиотеки')).toHaveValue(/"threshold": 1/);
  const saved=page.waitForResponse(r=>r.url().endsWith('/versions')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Сохранить новую версию',exact:true}).click();
  const v3=await (await saved).json();expect(v3.version).toBe(3);expect(v3.params).toEqual({threshold:1});
  expect((await (await request.get(`/api/check-library/${v1.check_id}/versions/2`)).json()).params).toEqual({threshold:2});
});

test('versioned library: frozen run, custom results, code, export, archive and restore', async ({page,browser,baseURL})=>{
  const name='Лимит изменений '+Date.now();
  const request=page.request;
  expect((await provisionAccount(request,{data:{username:'library-'+Date.now(),display_name:'Версии проверок',password:'Library-browser-password-42'}})).status()).toBe(201);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/?view=library');await page.getByRole('button',{name:'Проверки',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Библиотека проверок',exact:true})).toBeVisible();
  await page.getByLabel('Название проверки',{exact:true}).fill(name);
  await page.getByLabel('Параметры библиотеки').fill('{"max_share":0.1}');
  const creation=page.waitForResponse(r=>r.url().endsWith('/api/check-library')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Сохранить v1',exact:true}).click();
  const v1=await (await creation).json();
  await expect(page.getByRole('status')).toContainText('Сохранена версия 1');
  await page.getByLabel('Параметры библиотеки').fill('{"max_share":0.9}');
  const publishing=page.waitForResponse(r=>r.url().endsWith('/versions')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Сохранить новую версию',exact:true}).click();
  const v2=await (await publishing).json();expect(v2.version).toBe(2);
  await expect(page.getByRole('status')).toContainText('Сохранена версия 2');
  await page.getByLabel('Версия проверки',{exact:true}).selectOption('1');
  await expect(page.getByLabel('Параметры библиотеки')).toHaveValue(/0.1/);
  await page.screenshot({path:'../artifacts/library.png',fullPage:true});
  // Another account cannot read either version, even with an exact URL.
  const other=await browser.newContext({baseURL,extraHTTPHeaders:{'X-Balance-Request':'1'}});
  await provisionAccount(other.request,{data:{username:'other-library-'+Date.now(),display_name:'Other',password:'Library-browser-password-42'}});
  expect((await other.request.get(`/api/check-library/${v1.check_id}/versions/1`)).status()).toBe(404);
  await other.close();
  await page.getByRole('button',{name:'Обзор',exact:true}).click();
  await page.getByRole('button',{name:'Новый запуск',exact:true}).click();
  await page.getByLabel('Название запуска',{exact:true}).fill('Отчёт с версией 1');
  await page.getByRole('checkbox',{name:'Включить '+name,exact:true}).check();
  await page.getByLabel('Версия '+name,{exact:true}).selectOption(v1.id);
  const createRun=page.waitForResponse(r=>r.url().endsWith('/api/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Запустить',exact:true}).click();
  const run=await (await createRun).json();
  expect(run.check_plan.find((c:any)=>c.kind==='python').version).toBe(1);
  // Archiving after enqueue must not alter the frozen plan or prevent its execution.
  expect((await request.post(`/api/check-library/${v1.check_id}/archive`,{data:{archived:true}})).status()).toBe(200);
  await expect.poll(async()=>{const r=await (await request.get('/api/runs/'+run.id)).json();if(['failed','timed_out'].includes(r.status))throw new Error(r.error);return r.status;},{timeout:150000,intervals:[1000]}).toBe('completed');
  const result=await (await request.get('/api/runs/'+run.id)).json();
  expect(result.summary.checks_total).toBe(6);
  expect(result.checks.length).toBe(33);
  const custom=result.checks.find((r:any)=>r.CHECK_KIND==='python');
  expect(custom.RESULT).toBe('FAIL');expect(custom.CNT).toBe(502);expect(custom.CHECK_VERSION).toBe(1);
  await page.getByRole('button',{name:'Проверки',exact:true}).click();
  await reveal(page,'Состав проверок');
  const plan=page.locator('.plan-row').filter({hasText:name});
  await expect(plan).toContainText('v1');await expect(plan).toContainText('Выполнена');
  await plan.getByRole('button',{name:'Код и параметры',exact:true}).click();
  await expect(page.locator('.snapshot')).toContainText('0.1');
  await expect(page.locator('.snapshot')).toContainText('def run');
  const group=page.locator('.check-result-group').filter({hasText:name});await group.locator('summary').click();
  const row=group.locator('tbody tr').filter({hasText:'Доля изменившихся заявок'});
  await expect(row).toContainText('FAIL');await expect(row).toContainText('502');
  await row.getByRole('button',{name:/заяв/}).click();
  await expect(page.locator('tbody tr')).toHaveCount(30);
  await page.goto(`/?run=${run.id}&tab=checks`);
  const exported=await (await request.get(`/api/runs/${run.id}/report.html`)).text();
  expect(exported).toContain(name+' · v1');expect(exported).toContain(v1.sha256);
  await page.screenshot({path:'../artifacts/library-report.png',fullPage:true});
  // Restore the library item and run immutable v2 separately: threshold 0.9 yields PASS.
  await openTool(page,'Библиотека');await page.getByRole('button',{name:'Проверки',exact:true}).click();
  await page.getByRole('checkbox',{name:'Показать архив',exact:true}).check();
  await page.locator('.library-item').filter({hasText:name}).click();
  await page.getByRole('button',{name:'Восстановить',exact:true}).click();
  await page.getByLabel('Версия проверки',{exact:true}).selectOption('2');
  const trialResponse=page.waitForResponse(r=>r.url().endsWith('/versions/2/test'));
  await page.getByRole('button',{name:'Проверить v2',exact:true}).click();
  const trial=await (await trialResponse).json();
  await expect.poll(async()=>(await (await request.get('/api/jobs/'+trial.id)).json()).status,{timeout:20000,intervals:[500]}).toBe('completed');
  const trialResult=await (await request.get('/api/jobs/'+trial.id)).json();
  expect(trialResult.result.rows[0].RESULT).toBe('PASS');
  expect((await (await request.get('/api/runs/'+run.id)).json()).checks.find((r:any)=>r.CHECK_KIND==='python').RESULT).toBe('FAIL');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:'../artifacts/library-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});
